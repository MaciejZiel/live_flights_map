"""Synthetic air traffic for demo mode.

Nothing in this module comes from a live or recorded feed. Every aircraft is
generated from a fixed seed: a fleet shuttles back and forth between real
airport locations along great-circle routes with a simple climb, cruise and
descent profile. Positions are a pure function of time, so the same seed
gives the same sky on every instance and the archive can be backfilled for
replay without storing any third-party data.

Callsigns start with ``DEMO``, registrations with ``SYN-`` and the origin
country is ``Synthetic``, so generated aircraft cannot be mistaken for real
flights in the UI, exports or the API.
"""

