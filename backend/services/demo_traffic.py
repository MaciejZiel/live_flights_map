@dataclass(frozen=True, slots=True)
class SyntheticFlight:
    icao24: str
    callsign: str
    registration: str
    type_code: str
    origin: dict[str, object]
    destination: dict[str, object]
    distance_km: float
    cruise_speed_kmh: float
    cruise_altitude_m: float
    leg_seconds: float
    turnaround_seconds: float
    phase_offset_seconds: float

    @property
    def cycle_seconds(self) -> float:
        return 2 * (self.leg_seconds + self.turnaround_seconds)


def _to_vector(latitude: float, longitude: float) -> tuple[float, float, float]:
    lat = math.radians(latitude)
    lon = math.radians(longitude)
    return (math.cos(lat) * math.cos(lon), math.cos(lat) * math.sin(lon), math.sin(lat))


def great_circle_km(a: dict[str, object], b: dict[str, object]) -> float:
    lat1, lon1 = math.radians(float(a["latitude"])), math.radians(float(a["longitude"]))
    lat2, lon2 = math.radians(float(b["latitude"])), math.radians(float(b["longitude"]))
    h = (
        math.sin((lat2 - lat1) / 2) ** 2
        + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2
    )
    return 2 * EARTH_RADIUS_KM * math.asin(min(1.0, math.sqrt(h)))


def interpolate_great_circle(
    a: dict[str, object],
    b: dict[str, object],
    fraction: float,
) -> tuple[float, float]:
    """Return (latitude, longitude) at ``fraction`` of the way from a to b."""
    va = _to_vector(float(a["latitude"]), float(a["longitude"]))
    vb = _to_vector(float(b["latitude"]), float(b["longitude"]))
    dot = max(-1.0, min(1.0, sum(x * y for x, y in zip(va, vb))))
    omega = math.acos(dot)
    if omega < 1e-9:
        return float(a["latitude"]), float(a["longitude"])
    sin_omega = math.sin(omega)
    wa = math.sin((1 - fraction) * omega) / sin_omega
    wb = math.sin(fraction * omega) / sin_omega
    x, y, z = (wa * pa + wb * pb for pa, pb in zip(va, vb))
    latitude = math.degrees(math.atan2(z, math.hypot(x, y)))
    longitude = math.degrees(math.atan2(y, x))
    return latitude, longitude


def initial_bearing(latitude: float, longitude: float, target: dict[str, object]) -> float:
    lat1, lon1 = math.radians(latitude), math.radians(longitude)
    lat2, lon2 = math.radians(float(target["latitude"])), math.radians(float(target["longitude"]))
    d_lon = lon2 - lon1
    x = math.sin(d_lon) * math.cos(lat2)
    y = math.cos(lat1) * math.sin(lat2) - math.sin(lat1) * math.cos(lat2) * math.cos(d_lon)
    return (math.degrees(math.atan2(x, y)) + 360.0) % 360.0


def build_fleet(flight_count: int, seed: int) -> tuple[SyntheticFlight, ...]:
    rng = random.Random(seed)
    europe = [airport for airport in AIRPORTS if airport["region"] == "europe"]
    world = [airport for airport in AIRPORTS if airport["region"] == "world"]
    europe_weights = [HUB_WEIGHTS.get(str(airport["iata"]), 1) for airport in europe]
    fleet: list[SyntheticFlight] = []

    while len(fleet) < max(flight_count, 0):
        roll = rng.random()
        if roll < 0.72:
            origin, destination = rng.choices(europe, weights=europe_weights, k=2)
        elif roll < 0.9:
            origin = rng.choices(europe, weights=europe_weights, k=1)[0]
            destination = rng.choice(world)
        else:
            origin, destination = rng.sample(world, 2)

        distance_km = great_circle_km(origin, destination)
        if origin is destination or distance_km < 250:
            continue

        index = len(fleet)
        long_haul = distance_km > 3000
        cruise_speed_kmh = rng.uniform(820, 910) if long_haul else rng.uniform(700, 820)
        cruise_altitude_m = (
            rng.choice((10360, 10970, 11580, 12190))
            if long_haul
            else rng.choice((8530, 9140, 10060, 10670, 11280))
        )
        leg_seconds = distance_km / cruise_speed_kmh * 3600 + 15 * 60
        turnaround_seconds = rng.uniform(60, 100) * 60 if long_haul else rng.uniform(20, 40) * 60
        cycle_seconds = 2 * (leg_seconds + turnaround_seconds)
        fleet.append(
            SyntheticFlight(
                icao24=f"{0x5E0000 + index:06x}",
                callsign=f"{DEMO_CALLSIGN_PREFIX}{index + 1:03d}",
                registration=f"SYN-{index + 1:04d}",
                type_code=rng.choice(LONG_HAUL_TYPES if long_haul else SHORT_HAUL_TYPES),
                origin=origin,
                destination=destination,
                distance_km=distance_km,
                cruise_speed_kmh=cruise_speed_kmh,
                cruise_altitude_m=float(cruise_altitude_m),
                leg_seconds=leg_seconds,
                turnaround_seconds=turnaround_seconds,
                phase_offset_seconds=rng.uniform(0, cycle_seconds),
            )
        )

    return tuple(fleet)


def flight_leg_at(flight: SyntheticFlight, timestamp: float) -> tuple[dict, dict, float | None]:
    """Return (from, to, fraction flown) at ``timestamp``; fraction is None on the ground at ``to``."""
    phase = (timestamp + flight.phase_offset_seconds) % flight.cycle_seconds
    if phase < flight.leg_seconds:
        return flight.origin, flight.destination, phase / flight.leg_seconds
    phase -= flight.leg_seconds
    if phase < flight.turnaround_seconds:
        return flight.origin, flight.destination, None
    phase -= flight.turnaround_seconds
    if phase < flight.leg_seconds:
        return flight.destination, flight.origin, phase / flight.leg_seconds
    return flight.destination, flight.origin, None


def flight_state_at(flight: SyntheticFlight, timestamp: float) -> dict[str, object]:
    departure, arrival, fraction = flight_leg_at(flight, timestamp)
    base = {
        "icao24": flight.icao24,
        "callsign": flight.callsign,
        "origin_country": DEMO_ORIGIN_COUNTRY,
        "registration": flight.registration,
        "type_code": flight.type_code,
        "last_contact": int(timestamp),
        "synthetic": True,
    }

    if fraction is None:
        return {
            **base,
            "latitude": round(float(arrival["latitude"]), 5),
            "longitude": round(float(arrival["longitude"]), 5),
            "true_track": None,
            "altitude": 0.0,
            "velocity": 0.0,
            "vertical_rate": 0.0,
            "on_ground": True,
        }

    latitude, longitude = interpolate_great_circle(departure, arrival, fraction)
    flown_km = fraction * flight.distance_km
    remaining_km = flight.distance_km - flown_km
    climb_km, descent_km = 180.0, 230.0
    climb_ratio = min(1.0, flown_km / climb_km)
    descent_ratio = min(1.0, remaining_km / descent_km)
    altitude = flight.cruise_altitude_m * min(climb_ratio, descent_ratio)
    speed_ms = flight.cruise_speed_kmh / 3.6 * (0.55 + 0.45 * min(climb_ratio, descent_ratio))

    if climb_ratio < 1.0 and climb_ratio <= descent_ratio:
        vertical_rate = flight.cruise_altitude_m / (climb_km / (flight.cruise_speed_kmh / 3600) * 0.8)
    elif descent_ratio < 1.0:
        vertical_rate = -flight.cruise_altitude_m / (descent_km / (flight.cruise_speed_kmh / 3600) * 0.8)
    else:
        vertical_rate = 0.0

    return {
        **base,
        "latitude": round(latitude, 5),
        "longitude": round(longitude, 5),
        "true_track": round(initial_bearing(latitude, longitude, arrival), 1),
        "altitude": round(max(altitude, 150.0), 1),
        "velocity": round(speed_ms, 1),
        "vertical_rate": round(vertical_rate, 1),
        "on_ground": False,
    }


def _in_bbox(flight: dict[str, object], bbox: dict[str, float]) -> bool:
    latitude = float(flight["latitude"])
    longitude = float(flight["longitude"])
    if not bbox["lamin"] <= latitude <= bbox["lamax"]:
        return False
    if bbox["lomin"] <= bbox["lomax"]:
        return bbox["lomin"] <= longitude <= bbox["lomax"]
    return longitude >= bbox["lomin"] or longitude <= bbox["lomax"]


class SyntheticTrafficProvider:
    """FlightProvider that generates deterministic synthetic traffic."""

    name = "demo"

    def __init__(self, flight_count: int = 900, seed: int = 20260311, clock=time.time) -> None:
        self.fleet = build_fleet(flight_count, seed)
        self._by_callsign = {flight.callsign: flight for flight in self.fleet}
        self._clock = clock

    def snapshot_at(self, timestamp: float, bbox: dict[str, float]) -> dict[str, object]:
        flights = [
            state
            for state in (flight_state_at(flight, timestamp) for flight in self.fleet)
            if _in_bbox(state, bbox)
        ]
        return {
            "fetched_at": datetime.fromtimestamp(timestamp, tz=timezone.utc).isoformat(),
            "bbox": dict(bbox),
            "count": len(flights),
            "flights": flights,
        }

    def fetch_flights(self, bbox: dict[str, float]) -> dict[str, object]:
        return self.snapshot_at(self._clock(), bbox)

    def find(self, callsign: str | None) -> SyntheticFlight | None:
        if not callsign:
            return None
        return self._by_callsign.get(callsign.strip().upper())

    def current_leg(self, callsign: str | None) -> tuple[dict, dict] | None:
        flight = self.find(callsign)
        if flight is None:
            return None
        departure, arrival, _ = flight_leg_at(flight, self._clock())
        return departure, arrival


def _route_airport(airport: dict[str, object]) -> dict[str, object]:
    return {key: airport[key] for key in ("icao", "iata", "name", "location", "country_iso2", "latitude", "longitude")}


class SyntheticRouteClient:
    """Route lookup for synthetic callsigns; never calls an external service."""

    def __init__(self, provider: SyntheticTrafficProvider) -> None:
        self.provider = provider

    def lookup_route(self, callsign: str, latitude=None, longitude=None) -> dict[str, object] | None:
        leg = self.provider.current_leg(callsign)
        if leg is None:
            return None
        departure, arrival = leg
        airports = [_route_airport(departure), _route_airport(arrival)]
        flight_number = str(callsign).strip().upper()[len(DEMO_CALLSIGN_PREFIX):]
        return {
            "callsign": str(callsign).strip().upper(),
            "airline_code": DEMO_CALLSIGN_PREFIX,
            "airline_name": DEMO_AIRLINE_NAME,
            "flight_number": flight_number,
            "airport_codes": f"{departure['icao']}-{arrival['icao']}",
            "iata_codes": f"{departure['iata']}-{arrival['iata']}",
            "origin": airports[0],
            "destination": airports[-1],
            "stops": [],
            "airports": airports,
            "plausible": True,
            "route_label": f"{departure['iata']} -> {arrival['iata']}",
            "route_verbose": f"{departure['location']} -> {arrival['location']}",
        }


class NoPhotoClient:
    """Photo lookup that never leaves the process; synthetic aircraft have no photos."""

    def fetch_photo(self, registration, **_kwargs) -> None:
        return None
